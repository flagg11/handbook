def main():
    d = os.path.join(tmp, "pdf"); os.makedirs(d)
    index.init_db(); index.seed_folders(classify.FOLDER_TREE)
    # обучающие документы - те же, что лежат в папках по умолчанию
    man = json.load(open(os.path.join(ROOT, "samples", "manifest.json"), encoding="utf-8"))
    for m in man:
        pid = "s-" + uuid.uuid4().hex[:6]; p = os.path.join(ROOT, "samples", m["file"])
        index.add_document(pid, m["folder"], m["file"], p, 1, "-", sample=True); hb.ingest(pid)
    ids = {}
    for fname, want, blocks in BLIND:
        ms.render({"blocks": blocks, "scan": None}, d, fname)
        pid = "b-" + fname[:3]
        index.add_document(pid, index.INBOX, fname, os.path.join(d, fname), 1, "-", sample=True); hb.ingest(pid)
        ids[fname] = (pid, want)
    exact = safe = wrong = 0
    for fname, (pid, want) in ids.items():
        dec = classify.classify_document(pid)
        got = dec["folder"]
        verdict = "верно" if got == want else ("во Входящие (осторожно)" if got == index.INBOX else "ОШИБКА")
        if got == want: exact += 1
        elif got == index.INBOX: safe += 1
        else: wrong += 1
        print(f"{fname} ожидалось {want:14} получено {got:14} {dec['confidence']:.2f}  {verdict}  {'' if got == want else dec['reason']}")
    n = len(ids)
    print(f"\nВсего {n}: верно {exact}, осторожно во Входящие {safe}, в неверную папку {wrong}")


if __name__ == "__main__":
    main()
