def main():
    import shutil
    import extra_docs
    extra_docs.register(add, T)
    manifest, expected = [], {}
    for filename, spec, folder, author, date, where in DOCS:
        d = OUT if where == "samples" else DEMO
        render(spec, d, filename)
        if where == "samples":
            manifest.append({"file": filename, "folder": folder, "author": author, "date": date})
        expected[filename] = folder
    for f in sorted(os.listdir(OUT)):
        if f.startswith("_"):
            os.remove(os.path.join(OUT, f))
    with open(os.path.join(OUT, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, ensure_ascii=False, indent=2)
    with open(os.path.join(OUT, "truth.json"), "w", encoding="utf-8") as fh:
        json.dump(TRUTH, fh, ensure_ascii=False, indent=2)
    with open(os.path.join(OUT, "expected_folders.json"), "w", encoding="utf-8") as fh:
        json.dump(expected, fh, ensure_ascii=False, indent=2)
    for d in (OUT, DEMO):
        for f in sorted(os.listdir(d)):
            if f.endswith(".pdf"):
                print(os.path.basename(d), f, os.path.getsize(os.path.join(d, f)))
    shutil.rmtree(os.path.join(ROOT, "__pycache__"), ignore_errors=True)


if __name__ == "__main__":
    main()
