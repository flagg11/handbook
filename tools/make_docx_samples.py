def font(run, pt, bold=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(pt)
    run.bold = bold


def build(item):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.left_margin, sec.right_margin, sec.top_margin, sec.bottom_margin = Cm(3), Cm(1.5), Cm(2), Cm(2)
    st = doc.styles["Normal"]
    st.font.name, st.font.size = "Times New Roman", Pt(14)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    for i, line in enumerate(item["title"].split("\n")):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(4 if i == 0 else 14)
        font(p.add_run(line), 14, bold=True)
    for head, paras in item["body"]:
        if head:
            p = doc.add_paragraph()
            p.paragraph_format.space_before, p.paragraph_format.space_after = Pt(8), Pt(4)
            font(p.add_run(head), 14, bold=True)
        for text in paras:
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            p.paragraph_format.first_line_indent = Cm(1.25)
            p.paragraph_format.space_after = Pt(3)
            font(p.add_run(text), 14)
    if item.get("table"):
        cap, rows = item["table"]
        p = doc.add_paragraph()
        p.paragraph_format.space_before, p.paragraph_format.space_after = Pt(8), Pt(3)
        font(p.add_run(cap), 14)
        t = doc.add_table(rows=len(rows), cols=len(rows[0]))
        t.style = "Table Grid"
        for i, row in enumerate(rows):
            for j, v in enumerate(row):
                cell = t.cell(i, j)
                cell.text = ""
                font(cell.paragraphs[0].add_run(v), 12, bold=(i == 0))
    if item.get("tail"):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.first_line_indent = Cm(1.25)
        font(p.add_run(item["tail"]), 14)
    doc.core_properties.title = item["file"].rsplit(".", 1)[0]
    doc.core_properties.author = ""
    return doc


def main():
    manifest_path = os.path.join(SAMPLES, "manifest.json")
    expected_path = os.path.join(SAMPLES, "expected_folders.json")
    with open(manifest_path, encoding="utf-8") as fh:
        manifest = json.load(fh)
    with open(expected_path, encoding="utf-8") as fh:
        expected = json.load(fh)
    names = {m["file"] for m in manifest}
    for item in DOCS:
        build(item).save(os.path.join(SAMPLES, item["file"]))
        if item["file"] not in names:
            manifest.append({"file": item["file"], "folder": item["folder"], "author": item["author"], "date": item["date"]})
        expected[item["file"]] = item["folder"]
    with open(manifest_path, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, ensure_ascii=False, indent=2)
    with open(expected_path, "w", encoding="utf-8") as fh:
        json.dump(expected, fh, ensure_ascii=False, indent=2)
    print(f"Готово: {len(DOCS)} документов Word в {SAMPLES}")


if __name__ == "__main__":
    main()
